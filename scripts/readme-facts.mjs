// README FACTS GUARD  (npm run readme:sync  |  npm run readme:check)
//
// The README's "Repository facts" table is generated from the real tree, so it cannot silently drift.
//   node scripts/readme-facts.mjs --write   regenerate the block between the markers in README.md
//   node scripts/readme-facts.mjs --check   change nothing; exit 1 if the block is out of date
// tests/static/readme-facts.test.js runs the same check in CI (npm test), and also verifies that every
// "N home-screen widgets" claim in the README matches the widget XML on disk.

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const START = '<!-- repo-facts:start (generated by `npm run readme:sync` — do not edit by hand) -->';
export const END = '<!-- repo-facts:end -->';

function walk(dir, pred, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, pred, out);
    else if (pred(name, p)) out.push(p);
  }
  return out;
}

export function collectFacts(root = ROOT) {
  const dirs = (d) => existsSync(join(root, d))
    ? readdirSync(join(root, d)).filter((n) => statSync(join(root, d, n)).isDirectory()) : [];
  return {
    jsModules: walk(join(root, 'js'), (n) => n.endsWith('.js')).length,
    edgeFunctions: dirs('supabase/functions').length,
    migrations: existsSync(join(root, 'supabase/migrations'))
      ? readdirSync(join(root, 'supabase/migrations')).filter((n) => n.endsWith('.sql')).length : 0,
    testFiles: walk(join(root, 'tests'), (n) => n.endsWith('.test.js')).length,
    widgets: walk(join(root, 'android-widget/app/src/main/res/xml'), (n) => /_widget_info\.xml$/.test(n)).length,
    workflows: walk(join(root, '.github/workflows'), (n) => /\.ya?ml$/.test(n)).length,
  };
}

export function renderBlock(f) {
  return [
    START,
    '| Repository fact | Count |',
    '|---|---|',
    `| JS modules under \`js/\` | ${f.jsModules} |`,
    `| Supabase Edge Functions | ${f.edgeFunctions} |`,
    `| Dated SQL migrations | ${f.migrations} |`,
    `| Test files (\`*.test.js\`) | ${f.testFiles} |`,
    `| Android home-screen widgets | ${f.widgets} |`,
    `| GitHub Actions workflows | ${f.workflows} |`,
    END,
  ].join('\n');
}

export function currentBlock(readme) {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  return a === -1 || b === -1 ? null : readme.slice(a, b + END.length);
}

export function widgetClaims(readme) {
  return [...readme.matchAll(/(\d+) home-screen widgets/g)].map((m) => Number(m[1]));
}

const isMain = process.argv[1] && join(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const path = join(ROOT, 'README.md');
  const readme = readFileSync(path, 'utf8');
  const want = renderBlock(collectFacts());
  const have = currentBlock(readme);
  if (process.argv.includes('--write')) {
    if (have === null) { console.error('README.md has no repo-facts markers.'); process.exit(1); }
    writeFileSync(path, readme.replace(have, want));
    console.log(have === want ? 'README facts already up to date.' : 'README facts updated.');
  } else if (have !== want) {
    console.error('README repo-facts block is out of date. Run: npm run readme:sync');
    process.exit(1);
  } else console.log('README facts OK.');
}
